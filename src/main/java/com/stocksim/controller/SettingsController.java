package com.stocksim.controller;

import com.stocksim.model.User;
import com.stocksim.model.UserSettings;
import com.stocksim.service.AuthService;
import com.stocksim.service.MarketService;
import com.stocksim.service.SettingsService;
import com.stocksim.ui.Dialogs;
import com.stocksim.ui.Ui;
import com.stocksim.util.ConfigLoader;
import com.stocksim.util.DataSeeder;
import com.stocksim.util.Formats;
import javafx.fxml.FXML;
import javafx.scene.control.CheckBox;
import javafx.scene.control.Label;
import javafx.scene.control.PasswordField;
import javafx.scene.control.TextField;
import javafx.scene.layout.GridPane;
import javafx.stage.DirectoryChooser;

import java.io.File;
import java.nio.file.Path;

public class SettingsController extends PageController {
    @FXML private GridPane profileGrid;
    @FXML private CheckBox confirmBox;
    @FXML private TextField exportField;
    @FXML private PasswordField currentField;
    @FXML private PasswordField newField;
    @FXML private PasswordField repeatField;
    @FXML private Label snapshotLabel;
    @FXML private PasswordField resetField;
    @FXML private Label dataLabel;
    private final SettingsService settings = new SettingsService();
    private final AuthService auth = new AuthService();
    private final MarketService market = new MarketService();

    private record Data(User user, UserSettings settings, String source, String snapshot) {
    }

    @Override
    public void refresh() {
        int id = userId();
        shell.load(() -> new Data(auth.refresh(id), settings.get(id), market.dataSource(),
                settings.readSnapshot(id).map(s -> "Last snapshot " + Formats.dateTime(s.savedAt()) + ": day "
                        + s.state().currentDay() + ", cash " + Formats.money(s.cash()) + ", total value "
                        + Formats.money(s.totalValue())).orElse("No snapshot saved yet.")), d -> {
            profileGrid.getChildren().clear();
            Ui.row(profileGrid, "Name", d.user().name());
            Ui.row(profileGrid, "Username", d.user().username());
            Ui.row(profileGrid, "Email", d.user().email());
            Ui.row(profileGrid, "Member since", Formats.dateTime(d.user().createdAt()));
            Ui.row(profileGrid, "Starting capital", Formats.money(d.user().startingCapital()));
            confirmBox.setSelected(d.settings().confirmTrades());
            exportField.setText(d.settings().exportDir() == null ? "" : d.settings().exportDir());
            exportField.setPromptText(Path.of(ConfigLoader.get("export.dir", "reports")).toAbsolutePath()
                    .toString());
            snapshotLabel.setText(d.snapshot());
            dataLabel.setText(DataSeeder.SOURCE_SYNTHETIC.equals(d.source())
                    ? "Prices are SYNTHETIC sample data generated by StockSim. They only illustrate how a market "
                    + "behaves and are not real prices of the named companies."
                    : "Prices were imported from your historical CSV file. Scenario movements and market events "
                    + "are hypothetical.");
        });
    }

    @FXML private void browse() {
        DirectoryChooser chooser = new DirectoryChooser();
        chooser.setTitle("Choose where reports are saved");
        File chosen = chooser.showDialog(exportField.getScene().getWindow());
        if (chosen != null) {
            exportField.setText(chosen.getAbsolutePath());
        }
    }

    @FXML private void savePreferences() {
        int id = userId();
        boolean confirm = confirmBox.isSelected();
        String dir = exportField.getText();
        shell.act(() -> settings.save(id, confirm, dir), "Preferences saved.");
    }

    @FXML private void changePassword() {
        int id = userId();
        String current = currentField.getText();
        String next = newField.getText();
        String repeat = repeatField.getText();
        shell.act(() -> auth.changePassword(id, current, next, repeat), "Password changed.");
        currentField.clear();
        newField.clear();
        repeatField.clear();
    }

    @FXML private void saveSnapshot() {
        int id = userId();
        shell.act(() -> settings.saveSnapshot(id),
                path -> shell.toast("Snapshot saved", path.toString(), "toast-success"));
    }

    @FXML private void reset() {
        if (!Dialogs.confirm("Reset your whole simulation?", "All holdings, transactions, scenario runs and "
                + "simulated prices are erased and your cash returns to the starting capital. This cannot be "
                + "undone.")) {
            return;
        }
        int id = userId();
        String password = resetField.getText();
        resetField.clear();
        shell.act(() -> settings.resetSimulation(id, password), "Your simulation has been reset.");
    }
}
